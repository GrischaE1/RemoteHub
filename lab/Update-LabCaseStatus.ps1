#Requires -Version 5.1
<#
.SYNOPSIS
    Sets each case's status in docs\test-lab-cases.md (the "St" column) and docs\test-lab-test-document.md (the
    "Status:" line) from the lab tests and their results, so the documents don't fall behind the lab.
.DESCRIPTION
    Only cases with a lab test (an It tagged with the case ID in lab\tests\) are changed:
      - it has run in the lab (any result - Get-LabCaseStatus.ps1)  -> automated (check mark), the test file named
      - it has never run                                            -> written, not yet run (half circle)
    Cases without a lab test keep what the documents say (planned, manual, not automated). A failing case stays
    "automated": the documents say what is covered, failures.txt and the console say what passes.
    Prints what it changed; -WhatIf changes nothing.
.EXAMPLE
    .\lab\Update-LabCaseStatus.ps1 -WhatIf
    .\lab\Update-LabCaseStatus.ps1 -Root C:\rh-artifacts\lab
#>
[CmdletBinding(SupportsShouldProcess)]
param(
    [string]$Root,
    [string]$DocsDir = (Join-Path (Split-Path $PSScriptRoot) 'docs')
)
Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

# the documents' symbols; this script stays ASCII (lab instructions)
$auto = [string][char]0x2705       # check mark
$written = [string][char]0x25D0    # half circle
$dash = [string][char]0x2013       # en dash

# case ID -> its test files, and the IDs that have run
$files = @{}
foreach ($f in @(& (Join-Path $PSScriptRoot 'Get-LabCatalog.ps1'))) {
    foreach ($c in $f.Cases) {
        if (-not $files.ContainsKey($c.Id)) { $files[$c.Id] = New-Object System.Collections.Generic.List[string] }
        if (-not $files[$c.Id].Contains($f.File)) { $files[$c.Id].Add($f.File) }
    }
}
$a = @{}
if ($Root) { $a.Root = $Root }
$ran = @{}
foreach ($s in @(& (Join-Path $PSScriptRoot 'Get-LabCaseStatus.ps1') @a)) { $ran[$s.Id] = $true }

function Save-Doc([string]$Path, [string]$Text) {
    if ($PSCmdlet.ShouldProcess($Path, 'Update the case status')) {
        [IO.File]::WriteAllText($Path, $Text, (New-Object Text.UTF8Encoding($false)))
    }
}

# --- test-lab-cases.md: | ID | Test | Pass when | How | P | St | (some rows have one more, empty, cell)
$casesPath = Join-Path $DocsDir 'test-lab-cases.md'
$text = [IO.File]::ReadAllText($casesPath)
$changes = New-Object System.Collections.Generic.List[string]
$priority = @{}
$text = [regex]::Replace($text, '(?m)^\| ([A-Z][A-Z0-9]*(?:-[A-Z0-9]+)*-\d{2,}) \|.*$', {
        param($m)
        $line = $m.Value.TrimEnd("`r")
        $cr = if ($m.Value.EndsWith("`r")) { "`r" } else { '' }
        $id = $m.Groups[1].Value
        if (-not $files.ContainsKey($id)) { return $m.Value }
        # cells split on "|" not escaped as "\|"; [6] is St
        $cells = [regex]::Split($line, '(?<!\\)\|')
        if ($cells.Count -lt 8) { return $m.Value }
        $priority[$id] = $cells[5].Trim()
        $want = if ($ran.ContainsKey($id)) { $auto } else { $written }
        # the right symbol with a note after it ("(partly)") is kept as it is
        if ($cells[6].Trim().StartsWith($want)) { return $m.Value }
        $changes.Add("$id  $($cells[6].Trim()) -> $want")
        $cells[6] = " $want "
        ($cells -join '|') + $cr
    })
if ($changes.Count) { Save-Doc $casesPath $text }
"test-lab-cases.md: $($changes.Count) status(es) changed"
$changes | ForEach-Object { "  $_" }

# --- test-lab-test-document.md: "#### <ID> . <name>" then "P2 . How: ... . Status: <status>"
$docPath = Join-Path $DocsDir 'test-lab-test-document.md'
$text = [IO.File]::ReadAllText($docPath)
$changes = New-Object System.Collections.Generic.List[string]
# (the line ends are matched by lookahead: "$" in .NET stops before "\n" only, the documents have "\r\n")
$text = [regex]::Replace($text, '(?m)^(#### ([A-Z][A-Z0-9]*(?:-[A-Z0-9]+)*-\d{2,})\b[^\r\n]*\r?\n)(P\d [^\r\n]*? Status: )([^\r\n]*)(?=\r?\n|\z)', {
        param($m)
        $id = $m.Groups[2].Value
        if (-not $files.ContainsKey($id)) { return $m.Value }
        $old = $m.Groups[4].Value
        $cr = ''
        $list = ($files[$id] | ForEach-Object { '`' + $_ + '`' }) -join ', '
        $new = if ($ran.ContainsKey($id)) { "$auto Automated $dash $list" } else { "$written Written, not yet run in the lab $dash $list" }
        if ($old -eq $new -or $old.StartsWith($new.Substring(0, 1))) { return $m.Value }
        $changes.Add("$id  $old -> $new")
        $m.Groups[1].Value + $m.Groups[3].Value + $new + $cr
    })
# the "Written, not yet run in the lab" overview: the cases with a test that never ran, by priority and test file
$open = @($files.Keys | Where-Object { -not $ran.ContainsKey($_) } | Sort-Object)
$section = New-Object Text.StringBuilder
[void]$section.Append("### Written, not yet run in the lab`r`n`r`n$written = the test exists but has not run in the lab yet. ")
[void]$section.Append("Regenerated by ``lab\Update-LabCaseStatus.ps1`` from the lab results.`r`n`r`n")
if (-not $open.Count) { [void]$section.Append("None - every case with a lab test has run.`r`n`r`n") }
foreach ($p in @($open | Group-Object { if ($priority.ContainsKey($_)) { $priority[$_] } else { '?' } } | Sort-Object Name)) {
    [void]$section.Append("<details><summary><b>P$($p.Name)</b>: $($p.Count) cases</summary>`r`n`r`n")
    foreach ($f in @($p.Group | Group-Object { $files[$_][0] } | Sort-Object Name)) {
        [void]$section.Append("- **$($f.Name)** ($($f.Count)): $($f.Group -join ', ')`r`n")
    }
    [void]$section.Append("`r`n</details>`r`n`r`n")
}
$before = $text
$text = [regex]::Replace($text, '(?ms)^### Written, not yet run in the lab\r?\n.*?(?=^### )', { param($m) $section.ToString() })
if ($text -ne $before) { $changes.Add('the "Written, not yet run in the lab" overview') }

if ($changes.Count) { Save-Doc $docPath $text }
"test-lab-test-document.md: $($changes.Count) change(s)"
$changes | ForEach-Object { "  $_" }
